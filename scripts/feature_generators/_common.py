"""Helpers for the feature generators: one generated addon is a dict of relative path -> file text."""

from __future__ import annotations

import textwrap

GENERATOR_NOTE = "Generated by scripts/generate_features.py ({module}); do not edit."

OPERATOR_RESULT = 'set[Literal["RUNNING_MODAL", "CANCELLED", "FINISHED", "PASS_THROUGH", "INTERFACE"]]'


def block(text: str) -> str:
    """Dedent a triple-quoted block and drop its first newline."""
    return textwrap.dedent(text).lstrip("\n")


def manifest(addon_id: str, name: str, tagline: str) -> str:
    return block(f'''
        schema_version = "1.0.0"

        id = "{addon_id}"
        version = "1.0.0"
        name = "{name}"
        tagline = "{tagline}"
        maintainer = "Blender Extension Developer Suite"
        type = "add-on"

        blender_version_min = "4.2.0"

        license = ["SPDX:GPL-3.0-or-later"]

        [build]
        paths_exclude_pattern = ["__pycache__/", "_expected/", "check_*.py", "ide_*.py"]
    ''')


def python_file(module: str, docstring: str, body: str) -> str:
    """A generated Python (or stub) file: docstring with the generator note, then the body (flush left)."""
    note = GENERATOR_NOTE.format(module=module)
    return f'"""{docstring}\n\n{note}\n"""\n\n{body.strip()}\n'


EXECUTION_CONTEXTS = ["INVOKE_DEFAULT", "INVOKE_REGION_WIN", "INVOKE_REGION_CHANNELS", "INVOKE_REGION_PREVIEW",
                      "INVOKE_AREA", "INVOKE_SCREEN", "EXEC_DEFAULT", "EXEC_REGION_WIN", "EXEC_REGION_CHANNELS",
                      "EXEC_REGION_PREVIEW", "EXEC_AREA", "EXEC_SCREEN"]


def literal(values: list[str]) -> str:
    return "Literal[" + ", ".join(f'"{v}"' for v in values) + "]"


def ops_operator_stub(name: str, idname_py: str, params: list[tuple[str, str]]) -> list[str]:
    """Reference-stub lines for one operator in a ``bpy.ops.<category>`` module: what the checker synthesises for
    ``bpy.ops.<category>.<name>``. ``params`` are (property, type that can be passed) pairs."""
    category, _, op = idname_py.partition(".")
    idname = f"{category.upper()}_OT_{op}"
    cls = f"_{name}_operator"
    kwargs = "".join(f", {p}: {t} = ..." for p, t in params)
    star = ", *" if params else ""
    return [
        f"class {cls}:",
        f"    def __call__(self, execution_context: _ExecutionContext = ..., undo: bool = ..., /{star}{kwargs}) "
        f"-> {OPERATOR_RESULT}: ...",
        "    def poll(self, execution_context: _ExecutionContext = ..., /) -> bool: ...",
        f'    def idname(self) -> Literal["{idname}"]: ...',
        f'    def idname_py(self) -> Literal["{idname_py}"]: ...',
        "    def get_rna_type(self) -> Struct: ...",
        "",
        f"{name}: {cls}",
    ]


def ops_module_stub(module: str, docstring: str, operators: list[list[str]], imports: list[str] = ()) -> str:
    """A ``bpy.ops.<category>`` reference stub made of ``ops_operator_stub`` blocks."""
    lines = ["from collections.abc import Sequence", "from typing import Literal, TypeAlias", "",
             "from bpy.types import Struct", *imports, "",
             f"_ExecutionContext: TypeAlias = {literal(EXECUTION_CONTEXTS)}", ""]
    for operator in operators:
        lines += [*operator, ""]
    return python_file(module, docstring, "\n".join(lines))


def ops_package_delta(module: str, categories: list[str]) -> str:
    """The ``bpy.ops`` delta that makes new categories attributes of ``bpy.ops``."""
    lines = [f"from bpy.ops import {c} as {c}" for c in categories]
    return python_file(module, "Reference stub delta: the operator categories the addon adds to bpy.ops.",
                       "\n".join(lines))


def indent(lines: list[str], prefix: str = "    ") -> str:
    return "\n".join(prefix + line if line else line for line in lines)
